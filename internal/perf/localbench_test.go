//go:build localbench

// Hito X's opt-in performance benchmarks. They are behind TWO gates on
// purpose:
//
//  1. the `localbench` build tag, so `go test ./...` never compiles or runs
//     them (the repository already uses this tag for Hito I10's local
//     bandwidth benchmark);
//  2. GEOCAM_PERF=1, so even `go test -tags localbench ./...` does not start a
//     multi-minute measurement by accident.
//
// Typical invocation (from the repository root):
//
//	GEOCAM_PERF=1 GEOCAM_PERF_OUT=/tmp/geocam-perf \
//	  GEOCAM_PERF_MODELS_DIR=/path/to/models \
//	  GEOCAM_PERF_PYTHON=/path/to/python3 \
//	  go test -tags localbench ./internal/perf/ -run 'TestXPerformance' -v -count=1
//
// The untagged tests in this package are what CI runs: they prove the harness
// compiles and its counters work, and they produce no performance number.
package perf

